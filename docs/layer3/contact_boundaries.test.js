'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {analyze,intersection,crossings}=require('./contact_boundaries.js');
const original=fs.readFileSync(path.join(__dirname,'comparacion_visual_calf.html'),'utf8');
const match=original.match(/const stage=\$\('stage'\),M=(.*?);\n/);
assert(match);
const M=Function('return ('+match[1]+')')();
const actual=analyze(M),expected=require('./contact_boundaries_calf.qa.json');
assert.deepEqual(actual,expected);
assert.equal(actual.reviewPairs,4);
assert.equal(actual.pairs.reduce((n,p)=>n+p.frames.length,0),192);
assert.deepEqual(intersection([0,0],[2,2],[0,2],[2,0]),[1,1]);
assert.equal(intersection([0,0],[2,0],[0,1],[2,1]),null);
assert.equal(crossings([[0,0],[2,0],[2,2],[0,2]],[[1,-1],[3,-1],[3,1],[1,1]]).length,2);
console.log('PASS: 192 frame-pair boundary analyses; source JSON parity and intersection fixtures');
